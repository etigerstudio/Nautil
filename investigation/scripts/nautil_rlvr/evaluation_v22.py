DATASETS = ("validation_v1", "val_cf_removed", "val_cf_control")


def _rate(a, b):
    return a / b if b else None


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def scheduler_config(step: int, lora_name: str, adapter_dir: Path, ecfg: dict, paths: dict,
                     protocol_path: Path, endpoints: list[str], out_root: Path, samples: int) -> dict:
    cf = ecfg["counterfactual"]
    specs = {"validation_v1": (paths["val_bundle"], ecfg.get("val_case_ids")),
             "val_cf_removed": (cf["removed_bundle"], ecfg.get("cf_case_ids")),
             "val_cf_control": (cf["control_bundle"], ecfg.get("cf_case_ids"))}
    datasets = {}
    for name, (bundle, ids) in specs.items():
        bundle = refuse_test_path(Path(bundle))
        datasets[name] = {"bundle": str(bundle), "bundle_sha256": sha256_file(bundle), "split": "validation"}
        if ids:
            datasets[name]["case_ids"] = list(ids)
    return {
        "_how_to_read": "Generated by nautil_rlvr.evaluation_v22 for periodic validation of the RLVR adapter "
                        "(validation + validation counterfactual mini-set; never test data).",
        "run_name": f"rlvr_val_step{step:05d}", "output_root": str(out_root),
        "protocol": str(protocol_path),
        "prompt_variants": {"default": {"impl": "default", "system_prompt": str(paths["system_prompt"])}},
        "datasets": datasets,
        "backends": {"gpu": {"type": "vllm_completions", "tokenizer": ecfg.get("tokenizer") or str(paths["base_model"]),
                             "endpoints": [{"label": f"ep{i}", "url": url,
                                            "target_concurrency": int(ecfg.get("concurrency", 32))}
                                           for i, url in enumerate(endpoints)]}},
        "conditions": [{"name": f"rlvr_step{step:05d}", "backend": "gpu", "model": lora_name,
                        "adapter_path": str(adapter_dir), "prompt_variant": "default",
                        "fetch_policy": {"name": "own_choice"}, "evidence_transform": {"name": "full"},
                        "datasets": list(DATASETS), "samples": int(samples)}],
        "retry": {"max_attempts": 3, "backoff_seconds": 15},
        "status_interval_seconds": 120, "metrics_interval_seconds": 10,
        "sync": {"enabled": False}, "test_lock": {"frozen_protocol": None}}


def collect_dataset(out_root: Path, cond: str, dataset: str) -> list[dict]:
    d = Path(out_root) / cond / dataset
    return [json.loads(p.read_text()) for p in sorted(d.glob("*__s*.json")) if not p.name.endswith(".failed.json")]


def sample_index(rec: dict) -> int:
    return int((rec.get("job") or {}).get("sample_index", 0))


def decision(rec: dict):
    m = rec.get("conclusion_marker")
    return "closed" if m == "CASE CLOSED" else "not_closed" if m == "CASE NOT CLOSED" else None


def program_summary(records: list[dict], labels: dict[str, str]) -> dict:
    acc = collections.defaultdict(lambda: [0, 0])
    fetch_calls = fetch_invalid = 0
    for r in records:
        lab = labels[r["case_id"]]
        ok = decision(r) == lab
        prov = "host_teacher_label" if r["source"] == "host" else "report_label"
        for key in (f"all|{lab}", f"src_{r['source']}|{lab}", f"src_{r['source']}|all", f"{prov}|{lab}",
                    f"{prov}|all", "all|all"):
            acc[key][0] += ok
            acc[key][1] += 1
        for t in r.get("turns", []):
            if valid_fetch(t) or invalid_fetch(t):
                fetch_calls += 1
                fetch_invalid += invalid_fetch(t)
    a = {k: _rate(*v) for k, v in acc.items()}

    def bal(prefix):
        x, y = a.get(f"{prefix}|closed"), a.get(f"{prefix}|not_closed")
        return (x + y) / 2 if x is not None and y is not None else None
    n = len(records)
    finals = [r.get("final_answer") or "" for r in records]
    out = {"records": n, "cases": len({r["case_id"] for r in records}),
           "closure_acc": a.get("all|all"),
           "closure_acc_should_close": a.get("all|closed"), "closure_acc_should_not_close": a.get("all|not_closed"),
           "closure_balanced_acc": bal("all"),
           "closed_rate": _rate(sum(decision(r) == "closed" for r in records), n),
           "host_teacher_label": {"acc": a.get("host_teacher_label|all"), "should_close": a.get("host_teacher_label|closed"),
                                  "should_not_close": a.get("host_teacher_label|not_closed"),
                                  "balanced": bal("host_teacher_label"), "n": acc["host_teacher_label|all"][1]},
           "report_label": {"acc": a.get("report_label|all"), "should_close": a.get("report_label|closed"),
                            "should_not_close": a.get("report_label|not_closed"),
                            "balanced": bal("report_label"), "n": acc["report_label|all"][1]},
           "by_source": {s: {"acc": a.get(f"src_{s}|all"), "should_close": a.get(f"src_{s}|closed"),
                             "should_not_close": a.get(f"src_{s}|not_closed"), "n": acc[f"src_{s}|all"][1]}
                         for s in sorted({r["source"] for r in records})},
           "valid_citation_rate": _rate(sum(r.get("final_citations_all_disclosed") is True for r in records), n),
           "invalid_fetch_rate": _rate(fetch_invalid, fetch_calls), "fetch_calls_per_case": _rate(fetch_calls, n),
           "missing_marker_rate": _rate(sum(decision(r) is None for r in records), n),
           "final_rate": _rate(sum(r.get("status") == "final" for r in records), n),
           "turn_limit_rate": _rate(sum(r.get("status") == "turn_limit" for r in records), n),
           "turns_per_case": _rate(sum(r.get("assistant_turns", 0) for r in records), n),
           "answer_chars_mean": _mean([len(f) for f in finals]),
           "counts": {"should_close": acc["all|closed"][1], "should_not_close": acc["all|not_closed"][1]}}
    return out


def counterfactual_summary(val_records: list[dict], removed: list[dict], control: list[dict], cf_ids: list[str]) -> dict:
    ids = set(cf_ids)
    full = [r for r in val_records if r["case_id"] in ids]

    def closed_rate(rs):
        return _rate(sum(decision(r) == "closed" for r in rs), len(rs))

    def by_src(rs):
        g = collections.defaultdict(list)
        for r in rs:
            g[r["source"]].append(r)
        return {s: closed_rate(v) for s, v in sorted(g.items())}
    fr, rr, cr = closed_rate(full), closed_rate(removed), closed_rate(control)
    return {"cases": len(ids), "records": {"full": len(full), "removed": len(removed), "control": len(control)},
            "closed_rate_full": fr, "closed_rate_removed": rr, "closed_rate_control": cr,
            "removed_minus_control": (rr - cr) if rr is not None and cr is not None else None,
            "removed_minus_full": (rr - fr) if rr is not None and fr is not None else None,
            "missing_marker_rate_removed": _rate(sum(decision(r) is None for r in removed), len(removed)),
            "missing_marker_rate_control": _rate(sum(decision(r) is None for r in control), len(control)),
            "by_source": {"full": by_src(full), "removed": by_src(removed), "control": by_src(control)}}


def llm_scores(records: list[dict], judge, cases: dict, refs: dict, cfg) -> dict:
    from . import reward_v22
    futs, skipped = [], 0
    for rec in records:
        req = reward_v22.render_closure(rec, cases[rec["case_id"]], refs[rec["case_id"]], cfg.base)
        if req is None:
            skipped += 1
            continue
        futs.append((rec, judge.submit("closure", req[0], req[1], model_closed(rec))))
    rows, failed = [], 0
    for rec, fut in futs:
        out = fut.result()
        if "error" in out:
            failed += 1
            continue
        c = reward_v22.compute(rec, cases[rec["case_id"]], refs[rec["case_id"]], cfg, {"closure": out})
        con = out["conclusion"]
        rows.append({"case_id": rec["case_id"], "sample": sample_index(rec), "source": rec["source"],
                     "ref": refs[rec["case_id"]]["closure"], "decision": decision(rec),
                     "q_conc": c["components"]["q_conc"], "q_gap": c["components"]["q_gap"],
                     "outcome": c["dimensions"]["outcome"], "outcome_only_total": c["total"],
                     "C1a": con["C1a"]["answer"], "C1b": con["C1b"]["answer"], "C2": con["C2"]["answer"],
                     "C3_share": reward_v22.c3_score(con["C3"]["claims"]), "C3_claims": len(con["C3"]["claims"]),
                     "C4": con["C4"]["answer"],
                     **({f"{g}": out["gap"][g]["answer"] for g in ("G1", "G2", "G3")} if out.get("gap") else {})})
    yes = lambda q, v="yes": _rate(sum(r.get(q) == v for r in rows if q in r), sum(q in r for r in rows))
    summ = {"scored": len(rows), "failed": failed, "no_marker_skipped": skipped,
            "q_conc_mean": _mean([r["q_conc"] for r in rows]),
            "q_conc_mean_decided_closed": _mean([r["q_conc"] for r in rows if r["decision"] == "closed"]),
            "q_conc_mean_decided_not_closed": _mean([r["q_conc"] for r in rows if r["decision"] == "not_closed"]),
            "q_gap_mean": _mean([r["q_gap"] for r in rows]),
            "q_conc_mean_ref_closed": _mean([r["q_conc"] for r in rows if r["ref"] == "closed"]),
            "q_conc_mean_ref_not_closed": _mean([r["q_conc"] for r in rows if r["ref"] == "not_closed"]),
            "outcome_mean": _mean([r["outcome"] for r in rows]),
            "outcome_only_total_mean": _mean([r["outcome_only_total"] for r in rows]),
            "yes_C1a": yes("C1a"), "yes_C1b": yes("C1b"), "partial_C1b": yes("C1b", "partial"), "yes_C2": yes("C2"),
            "yes_C4": yes("C4"), "C3_supported_share_mean": _mean([r["C3_share"] for r in rows if r["C3_claims"]]),
            "C3_claims_mean": _mean([r["C3_claims"] for r in rows]),
            "yes_G1": yes("G1"), "yes_G2": yes("G2"), "yes_G3": yes("G3"),
            "judge_health": {k: v for k, v in judge.cumulative().items() if not isinstance(v, (dict, list))}}
    return {"summary": summ, "rows": rows}


def compare_judges(a: dict, b: dict) -> dict:
    ka = {(r["case_id"], r["sample"]): r for r in a["rows"]}
    kb = {(r["case_id"], r["sample"]): r for r in b["rows"]}
    both = sorted(set(ka) & set(kb))
    d = lambda f: _mean([ka[k][f] - kb[k][f] for k in both if ka[k][f] is not None and kb[k][f] is not None])
    agree = lambda q: _rate(sum(ka[k].get(q) == kb[k].get(q) for k in both), len(both))
    return {"paired": len(both), "luna_minus_sol_q_conc": d("q_conc"), "luna_minus_sol_outcome": d("outcome"),
            "luna_minus_sol_q_gap": _mean([ka[k]["q_gap"] - kb[k]["q_gap"] for k in both
                                           if ka[k]["q_gap"] is not None and kb[k]["q_gap"] is not None]),
            "mean_abs_diff_q_conc": _mean([abs(ka[k]["q_conc"] - kb[k]["q_conc"]) for k in both
                                           if ka[k]["q_conc"] is not None and kb[k]["q_conc"] is not None]),
            "agree_C1a": agree("C1a"), "agree_C1b": agree("C1b"), "agree_C2": agree("C2"), "agree_C4": agree("C4")}


def run_eval(step: int, lora_name: str, adapter_dir: Path, ecfg: dict, paths: dict, protocol_path: Path,
             endpoints: list[str], run_dir: Path, samples: int) -> tuple[dict, list[dict]]:
    out_root = Path(run_dir) / "eval" / f"step_{step:05d}"
    out_root.mkdir(parents=True, exist_ok=True)
    cfg = scheduler_config(step, lora_name, adapter_dir, ecfg, paths, protocol_path, endpoints,
                           out_root / "scheduler_out", samples)
    cfg_path = out_root / "scheduler_config.json"
    atomic_json(cfg_path, cfg)
    code = run_scheduler(cfg_path, ecfg, out_root / "scheduler.log")
    cond = cfg["conditions"][0]["name"]
    recs = {ds: collect_dataset(out_root / "scheduler_out", cond, ds) for ds in DATASETS}
    labels = val_labels(Path(paths["val_refs"]))
    cf_ids = ecfg.get("cf_case_ids") or [r["case_id"] for r in read_jsonl(refuse_test_path(Path(ecfg["counterfactual"]["removed_bundle"])))]
    val = recs["validation_v1"]
    s0 = [r for r in val if sample_index(r) == 0]
    summary = {"step": step, "lora_name": lora_name, "scheduler_exit_code": code, "samples": samples,
               "program": program_summary(val, labels) if val else {"records": 0},
               "counterfactual": counterfactual_summary(val, recs["val_cf_removed"], recs["val_cf_control"], cf_ids)}
    if samples > 1:
        summary["program_sample0"] = program_summary(s0, labels) if s0 else {"records": 0}
        summary["counterfactual_sample0"] = counterfactual_summary(
            s0, [r for r in recs["val_cf_removed"] if sample_index(r) == 0],
            [r for r in recs["val_cf_control"] if sample_index(r) == 0], cf_ids)
    atomic_json(out_root / "summary.json", summary)
    return summary, s0
